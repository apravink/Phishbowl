#!/usr/bin/env node
/** Generate extension/src/background/tranco.gen.ts from the Tranco top-1M
 *  ranking (tranco-list.eu — DistriNet, KU Leuven). Run:
 *    pnpm fetch:tranco
 *  COMMIT the output (build-time data ⇒ NFR-1 clean, no runtime fetch).
 *  Regenerate quarterly alongside extension releases (REQ-4). The permanent
 *  list ID is pinned in the header for reproducibility, same spirit as
 *  jev-1.14.0. No API key: the daily zip URL is public. */
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { unzipSync } from "fflate";

const TOP_N = 20_000; // REQ-4: top-20k, ~300 KB
const ZIP_URL = "https://tranco-list.eu/top-1m.csv.zip";
const ID_URL = "https://tranco-list.eu/top-1m-id";
const OUT = resolve(
  dirname(fileURLToPath(import.meta.url)),
  "../extension/src/background/tranco.gen.ts",
);

const zipRes = await fetch(ZIP_URL);
if (!zipRes.ok) throw new Error(`zip fetch ${zipRes.status} for ${ZIP_URL}`);
const zipBuf = new Uint8Array(await zipRes.arrayBuffer());
const files = unzipSync(zipBuf);
const csvName = Object.keys(files).find((n) => n.endsWith(".csv"));
if (!csvName) throw new Error(`no .csv inside zip: ${Object.keys(files)}`);

// Format: "rank,domain" per line — Alexa/Cisco Umbrella style.
const csv = new TextDecoder().decode(files[csvName]);
const domains = [];
for (const line of csv.split("\n")) {
  const comma = line.indexOf(",");
  if (comma === -1) continue;
  domains.push(line.slice(comma + 1).trim().toLowerCase());
  if (domains.length === TOP_N) break;
}
if (domains.length !== TOP_N) throw new Error(`expected ${TOP_N}, got ${domains.length}`);

// Permanent list ID for citation/reproducibility (best-effort).
let listId = "unknown";
try {
  const idRes = await fetch(ID_URL);
  if (idRes.ok) listId = (await idRes.text()).trim();
} catch { /* non-fatal */ }

writeFileSync(
  OUT,
  `// AUTO-GENERATED by scripts/fetch-tranco.mjs — DO NOT EDIT BY HAND\n` +
    `// Source: Tranco top-${TOP_N} of the top-1M daily list, list ID ${listId}, fetched ${new Date().toISOString()}\n` +
    `// tranco-list.eu — Le Pochat et al., NDSS 2019. Data attributions: PLAN.md Phase 8.\n` +
    `export const TRANCO: ReadonlySet<string> = new Set([\n` +
    domains.map((d) => `  "${d}",`).join("\n") +
    `\n]);\n`,
);
console.log(`wrote ${domains.length} domains (list ${listId}) to ${OUT}`);
