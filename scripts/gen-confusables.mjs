#!/usr/bin/env node
/** Generate extension/src/background/confusables.gen.ts from Unicode UTS#39
 *  confusables.txt. Run: node scripts/gen-confusables.mjs — COMMIT the output
 *  (build-time data ⇒ NFR-1 clean, no runtime fetch). Pin the Unicode
 *  revision and bump it deliberately, like jev-1.14.0 in PLAN.md. */
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const REVISION = "16.0.0";
const SRC = `https://www.unicode.org/Public/security/${REVISION}/confusables.txt`;
const OUT = resolve(
  dirname(fileURLToPath(import.meta.url)),
  "../extension/src/background/confusables.gen.ts",
);

const res = await fetch(SRC);
if (!res.ok) throw new Error(`fetch ${res.status} for ${SRC}`);
const text = await res.text();

const parsed = [];
for (const line of text.split("\n")) {
  // format: <source> ; <target(s)> # comment   (hex code points, space-separated)
  const m = line.match(/^([0-9A-F]+)\s*;\s*((?:[0-9A-F]+ )*[0-9A-F]+)/);
  if (!m) continue; // blank lines, comments, headers
  const from = parseInt(m[1], 16);
  const toCps = m[2].trim().split(/\s+/).map((h) => parseInt(h, 16));
  if (toCps.length !== 1) continue; // multi-char skeletons out of scope for v1
  const to = String.fromCodePoint(toCps[0]);
  if (!/^[a-z0-9]$/i.test(to)) continue; // keep only ASCII-alphanumeric targets
  parsed.push({ from, to: to.toLowerCase() });
}

parsed.sort((a, b) => a.from - b.from); // deterministic, diffable output

const esc = (cp) =>
  cp > 0xffff
    ? `"\\u{${cp.toString(16).toUpperCase()}}"`
    : `"\\u${cp.toString(16).toUpperCase().padStart(4, "0")}"`;

const rows = parsed.map((e) => `  [${esc(e.from)}, "${e.to}"],`).join("\n");

writeFileSync(
  OUT,
  `// AUTO-GENERATED by scripts/gen-confusables.mjs — DO NOT EDIT BY HAND\n` +
    `// Source: Unicode UTS#39 confusables.txt, revision ${REVISION}\n` +
    `// Filter: single-codepoint sources whose skeleton is one ASCII alphanumeric\n` +
    `export const UNICODE_CONFUSABLES = new Map<string, string>([\n${rows}\n]);\n`,
);
console.log(`wrote ${parsed.length} mappings to ${OUT}`);
